function parsePath(d) {
  const parts = d.match(/[a-zA-Z][^a-zA-Z]*/g);
  return parts.map(p => {
    const cmd = p[0];
    const args = p.slice(1).trim().split(/[\s,]+/).map(parseFloat).filter(n => !isNaN(n));
    return { cmd, args };
  });
}

function alignPaths(sourceD, targetD) {
  const s = parsePath(sourceD);
  let t = parsePath(targetD);
  let aligned = '';
  let tIdx = 0;
  
  let lastX = 0, lastY = 0;
  function updateLast(cmdInfo) {
    if (cmdInfo.args.length >= 2) {
      lastX = cmdInfo.args[cmdInfo.args.length - 2];
      lastY = cmdInfo.args[cmdInfo.args.length - 1];
    }
  }

  for (let i = 0; i < s.length; i++) {
    const sCmd = s[i].cmd;
    let tCmd = (t[tIdx] || {}).cmd;
    
    if (sCmd === tCmd) {
      aligned += tCmd + t[tIdx].args.join(' ');
      updateLast(t[tIdx]);
      tIdx++;
    } else {
      if (sCmd === 'C' && tCmd === 'L') {
        // Source has C, target has L. We can convert Target L to C
        const x = t[tIdx].args[0];
        const y = t[tIdx].args[1];
        aligned += "C" + lastX + " " + lastY + " " + x + " " + y + " " + x + " " + y;
        lastX = x;
        lastY = y;
        tIdx++;
      } else if (sCmd === 'L' && tCmd === 'C') {
        // Source has L, target has C. We consume Target C as C?
        // Wait, if Source has L, we MUST output an L to match Source's structure.
        // We can output L using Target's C endpoint.
        const len = t[tIdx].args.length;
        const x = t[tIdx].args[len - 2];
        const y = t[tIdx].args[len - 1];
        aligned += "L" + x + " " + y;
        lastX = x;
        lastY = y;
        tIdx++;
      } else if (sCmd === 'L' && !tCmd) {
        aligned += "L" + lastX + " " + lastY;
      } else if (sCmd === 'C' && !tCmd) {
        aligned += "C" + lastX + " " + lastY + " " + lastX + " " + lastY + " " + lastX + " " + lastY;
      } else if (sCmd === 'Z' || sCmd === 'z') {
        aligned += sCmd;
        if (tCmd === 'Z' || tCmd === 'z') tIdx++;
      } else {
        // fallback
        if (t[tIdx]) {
           aligned += tCmd + t[tIdx].args.join(' ');
           updateLast(t[tIdx]);
           tIdx++;
        }
      }
    }
  }
  
  return aligned;
}

