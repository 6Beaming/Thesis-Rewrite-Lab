#!/usr/bin/env node
"use strict";

/**
 * Emit CSS custom properties for owl container layouts at a given render width.
 *
 * Usage:
 *   node scripts/transform-container-layout.cjs --variant desktop --width 240
 *   node scripts/transform-container-layout.cjs --variant mobile --width 128 --output src/styles/generated/owl-container-vars.css
 */

const fs = require("fs");
const path = require("path");

const repoRoot = path.resolve(__dirname, "..");

function readArg(name, fallback) {
  const idx = process.argv.indexOf(name);
  if (idx === -1 || process.argv[idx + 1] === undefined) {
    return fallback;
  }
  return process.argv[idx + 1];
}

const variant = readArg("--variant", "desktop");
const width = Number(readArg("--width", "512"));
const outputPath = readArg("--output", null);

const layoutPath = path.join(repoRoot, "scripts/generated/owl-container-layout.json");
const layout = JSON.parse(fs.readFileSync(layoutPath, "utf8"))[variant];

if (!layout) {
  console.error(`Unknown variant: ${variant}`);
  process.exit(1);
}

const height = width / layout.aspectRatio;
const indicatorWidth = width * layout.regions.indicator.widthRatio;

const css = `:root {
  /* Generated by scripts/transform-container-layout.cjs */
  --owl-layout-variant: ${variant};
  --owl-container-width: ${width.toFixed(4)}px;
  --owl-container-height: ${height.toFixed(4)}px;
  --owl-grid-rows: ${layout.gridTemplateRows};
  --owl-aspect-ratio: ${layout.aspectRatio};
  --owl-indicator-width: ${indicatorWidth.toFixed(4)}px;
}
`;

if (outputPath) {
  const resolved = path.resolve(repoRoot, outputPath);
  fs.mkdirSync(path.dirname(resolved), { recursive: true });
  fs.writeFileSync(resolved, css, "utf8");
  console.log(`Wrote ${path.relative(repoRoot, resolved)}`);
} else {
  process.stdout.write(css);
}
